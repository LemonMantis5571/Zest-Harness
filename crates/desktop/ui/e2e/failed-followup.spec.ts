import { expect, test } from "@playwright/test";

test("a late queue failure stays with its chat and preserves newer drafts", async ({ page }) => {
  await page.goto("/?fixture=1&scenario=split-streaming&holdQueueFailure=1");
  await page.getByRole("button", { name: /^Local model chat/ }).click();
  const input = page.locator("#zest-composer-input");
  await input.fill("Keep this turn open");
  await input.press("Enter");
  await expect(page.getByRole("button", { name: "Stop", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Add context" }).click();
  await page.getByRole("menuitem", { name: "Upload files" }).click();
  const pdf = page.getByText("sample.pdf", { exact: true });
  await expect(pdf).toBeVisible();
  await input.fill("Follow up in the original project");
  await input.press("Enter");
  await input.fill("Newer original draft");
  await page.getByRole("button", { name: "Fifteen turns", exact: true }).click();
  await expect(input).toHaveValue("");
  await input.fill("Other chat draft");
  await page.evaluate(() => window.dispatchEvent(new Event("zest:fixture-reject-queue")));
  await expect(page.getByText("Could not queue message", { exact: true })).toBeVisible();
  await expect(input).toHaveValue("Other chat draft");
  await expect(pdf).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Restore draft" })).toHaveCount(0);
  await page.getByRole("button", { name: /^Local model chat/ }).click();
  const restore = page.getByRole("button", { name: "Restore draft" });
  await expect(input).toHaveValue("Newer original draft");
  await expect(restore).toBeDisabled();
  await input.fill("");
  await restore.click();
  await expect(input).toHaveValue("Follow up in the original project");
  await expect(restore).toHaveCount(0);
  await expect(pdf).toBeVisible();
});
