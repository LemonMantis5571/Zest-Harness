// Regenerates the native app's Lucide icons from the React UI's lucide-react package, so both
// frontends draw the same glyphs. Run from the repository root after `npm ci`:
//   node spikes/gpui/assets/generate-icons.mjs
// Add a name to ICONS (lucide's kebab-case file name) and rerun to make it available as `Icon::*`.
import { copyFileSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ICONS = [
  "activity", "arrow-down", "arrow-left", "arrow-right", "arrow-up", "bell", "bot", "brain",
  "check", "chevron-down", "chevron-left", "chevron-right", "chevron-up", "chevrons-up-down",
  "circle", "circle-alert", "circle-check", "circle-dot", "circle-question-mark", "circle-stop", "circle-x",
  "clock", "code", "columns-2", "copy", "corner-down-left", "download", "ellipsis", "external-link",
  "eye", "file", "file-diff", "file-text", "files", "folder", "folder-git-2", "folder-open",
  "gauge", "git-branch", "git-commit-horizontal", "git-compare", "git-fork", "git-merge",
  "git-pull-request", "globe", "hammer", "history", "image", "layers", "layout-grid",
  "list-checks", "list-todo", "loader-circle", "lock", "maximize-2", "message-square",
  "minimize-2", "music", "network", "package", "panel-left", "panel-right", "paperclip",
  "palette", "pause", "pencil", "pin", "pin-off", "play", "plug", "plus", "puzzle", "refresh-cw",
  "rotate-ccw", "rows-2", "search", "send", "server", "settings", "shield", "shield-check",
  "skip-back", "skip-forward", "sliders-horizontal", "sparkles", "split", "square",
  "square-pen", "square-terminal", "sun", "terminal", "trash-2", "triangle-alert", "type", "user",
  "users", "wand-sparkles", "workflow", "wrench", "x", "zap",
];

const here = dirname(fileURLToPath(import.meta.url));
const lucide = join(here, "..", "..", "..", "node_modules", "lucide-react");
const out = join(here, "icons");
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
copyFileSync(join(lucide, "LICENSE"), join(out, "LICENSE"));

const attr = (attrs) =>
  Object.entries(attrs)
    .filter(([k]) => k !== "key")
    .map(([k, v]) => ` ${k.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)}="${v}"`)
    .join("");

const variants = [];
for (const name of ICONS) {
  // Renamed icons are re-exports of their new file.
  let file = join(lucide, "dist", "esm", "icons", `${name}.mjs`);
  const alias = readFileSync(file, "utf8").match(/export \{ default \} from '\.\/(.+?\.mjs)'/);
  if (alias) file = join(dirname(file), alias[1]);
  const { __iconData } = await import(pathToFileURL(file));
  const body = __iconData.node.map(([tag, attrs]) => `<${tag}${attr(attrs)}/>`).join("");
  writeFileSync(
    join(out, `${name}.svg`),
    `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="#000" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${body}</svg>\n`,
  );
  variants.push([name.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase()), name]);
}

const { version } = JSON.parse(readFileSync(join(lucide, "package.json"), "utf8"));
const rust = `// @generated by spikes/gpui/assets/generate-icons.mjs from lucide-react ${version} (ISC). Do not edit.

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Icon {
${variants.map(([v]) => `    ${v},`).join("\n")}
}

impl Icon {
    pub fn path(self) -> &'static str {
        match self {
${variants.map(([v, n]) => `            Icon::${v} => "icons/${n}.svg",`).join("\n")}
        }
    }
}

pub static FILES: &[(&str, &[u8])] = &[
${variants.map(([, n]) => `    ("icons/${n}.svg", include_bytes!("../assets/icons/${n}.svg")),`).join("\n")}
];
`;
writeFileSync(join(here, "..", "src", "icons_generated.rs"), rust);
console.log(`Wrote ${ICONS.length} icons (${readdirSync(out).length - 1} files).`);
